func TestLuaTemplate_Surface_Fallback(t *testing.T) {
	schema := EventSchema{
		PackageName: "surface",
		PackagePath: "client/surface",
		StructName:  "SurfaceEvent",
		Tags:        []string{"surface_created", "surface_deleted"},
		Fields: []FieldSchema{
			{Name: "Event", Type: "string", Position: -1, IsTag: true},
			{Name: "SurfaceName", Type: "string", Position: 0},
			{Name: "SurfaceIndex", Type: "int", Position: 1},
		},
		Lua: &LuaSchema{
			Events: []LuaEvent{
				{Name: "on_surface_created", Tag: "surface_created"},
				{Name: "on_surface_deleted", Tag: "surface_deleted"},
			},
			Fields: map[string]string{
				"SurfaceName":  "surface.name",
				"SurfaceIndex": "surface.index",
			},
			Guards:   []string{"game.surfaces[event.surface_index]"},
			Tag:      "surface_created",
			Defaults: map[string]string{},
			Fallback: &LuaFallback{
				Object: "surface",
				Defaults: map[string]string{
					"SurfaceName":  `""`,
					"SurfaceIndex": "event.surface_index",
				},
			},
		},
	}

	var buf bytes.Buffer
	err := luaTemplate.Execute(&buf, schema)
	require.NoError(t, err)

	output := buf.String()
	t.Log(output)

	// Verify surface_created handler (simple, no fallback)
	assert.Contains(t, output, "local function on_surface_created(event)")
	assert.Contains(t, output, `[surface_created]`)
	// Verify surface_deleted handler (with fallback)
	assert.Contains(t, output, "local function on_surface_deleted(event)")
	assert.Contains(t, output, "if surface and surface.valid then")
	assert.Contains(t, output, `[surface_deleted]`)
	// Verify fallback branch
	assert.Contains(t, output, "else")
	assert.Contains(t, output, "event.surface_index")
	// Verify registration
	assert.Contains(t, output, "surface_mod.events = {")
	assert.Contains(t, output, "[defines.events.on_surface_created] = on_surface_created,")
	assert.Contains(t, output, "[defines.events.on_surface_deleted] = on_surface_deleted,")
	assert.Contains(t, output, "return surface_mod")
}

func TestLuaTemplate_Tile_Iteration(t *testing.T) {
	schema := EventSchema{
		PackageName: "tile",
		PackagePath: "client/tile",
		StructName:  "TileEvent",
		Tags:        []string{"tile_built", "tile_mined"},
		Fields: []FieldSchema{
			{Name: "Event", Type: "string", Position: -1, IsTag: true},
			{Name: "Name", Type: "string", Position: 0},
			{Name: "X", Type: "float64", Position: 1},
			{Name: "Y", Type: "float64", Position: 2},
			{Name: "SurfaceName", Type: "string", Position: 3},
			{Name: "SurfaceIndex", Type: "int", Position: 4},
			{Name: "PlayerIndex", Type: "int", Position: 5},
		},
		Lua: &LuaSchema{
			Events: []LuaEvent{
				{Name: "on_player_built_tile", Tag: "tile_built"},
				{Name: "on_robot_built_tile", Tag: "tile_built"},
				{Name: "on_player_mined_tile", Tag: "tile_mined"},
				{Name: "on_robot_mined_tile", Tag: "tile_mined"},
			},
			Fields: map[string]string{
				"Name":         "tile.old_tile.name",
				"X":            "tile.position.x",
				"Y":            "tile.position.y",
				"SurfaceName":  "surface.name",
				"SurfaceIndex": "surface.index",
				"PlayerIndex":  "event.player_index",
			},
			Guards:   []string{"game.surfaces[event.surface_index]"},
			Iterate:  "event.tiles",
			LoopVar:  "tile",
			Tag:      "tile_built",
			Defaults: map[string]string{
				"PlayerIndex": "0",
			},
		},
	}

	var buf bytes.Buffer
	err := luaTemplate.Execute(&buf, schema)
	require.NoError(t, err)

	output := buf.String()
	t.Log(output)

	// Verify iteration pattern
	assert.Contains(t, output, "local function handle_tile_event(event, tag)")
	assert.Contains(t, output, "for _, tile in pairs(event.tiles)")
	// Verify guards
	assert.Contains(t, output, "if not (surface and surface.valid) then return end")
	// Verify handler functions
	assert.Contains(t, output, "local function on_player_built_tile(event)")
	assert.Contains(t, output, `handle_tile_event(event, "tile_built")`)
	assert.Contains(t, output, `handle_tile_event(event, "tile_mined")`)
	// Verify registration
	assert.Contains(t, output, "tile_mod.events = {")
	assert.Contains(t, output, "[defines.events.on_player_built_tile] = on_player_built_tile,")
	assert.Contains(t, output, "return tile_mod")
}
