func TestLuaTemplate_Game_NthTick(t *testing.T) {
	schema := EventSchema{
		PackageName: "game",
		PackagePath: "client/game",
		StructName:  "Tick",
		Tags:        []string{"game_tick"},
		Fields: []FieldSchema{
			{Name: "Tick", Type: "uint64", Position: 0},
		},
		Lua: &LuaSchema{
			Events:   []LuaEvent{{Name: "on_tick", Tag: "game_tick"}},
			Fields:   map[string]string{"Tick": "game.tick"},
			Guards:   nil,
			Tag:      "game_tick",
			NthTick:  60,
			Defaults: map[string]string{},
		},
	}

	var buf bytes.Buffer
	err := luaTemplate.Execute(&buf, schema)
	require.NoError(t, err)

	output := buf.String()
	t.Log(output)

	// Verify structure
	assert.True(t, strings.HasPrefix(output, "-- Code generated by go run ./gen -- DO NOT EDIT.\n"))
	assert.Contains(t, output, "local game_mod = {}")
	assert.Contains(t, output, "local TICK_INTERVAL = 60")
	assert.Contains(t, output, "local function on_tick(event)")
	assert.Contains(t, output, `string.format("[game_tick] %d", game.tick)`)
	assert.Contains(t, output, "helpers.send_udp(4000, msg, 0)")
	assert.Contains(t, output, "game_mod.on_nth_tick = {")
	assert.Contains(t, output, "[TICK_INTERVAL] = on_tick,")
	assert.Contains(t, output, "return game_mod")
	// Should NOT have events table
	assert.NotContains(t, output, "game_mod.events")
}

