func TestLuaTemplate_Entity_SharedEmitIncludeCause(t *testing.T) {
	schema := EventSchema{
		PackageName: "entity",
		PackagePath: "client/entity",
		StructName:  "EntityEvent",
		Tags:        []string{"entity_died", "entity_built", "entity_mined"},
		Fields: []FieldSchema{
			{Name: "Event", Type: "string", Position: -1, IsTag: true},
			{Name: "Name", Type: "string", Position: 0},
			{Name: "X", Type: "float64", Position: 1},
			{Name: "Y", Type: "float64", Position: 2},
			{Name: "UnitNumber", Type: "uint64", Position: 3},
			{Name: "SurfaceName", Type: "string", Position: 4},
			{Name: "SurfaceIndex", Type: "int", Position: 5},
			{Name: "PlayerIndex", Type: "int", Position: 6},
			{Name: "Cause", Type: "string", Position: 7, Optional: true},
		},
		Lua: &LuaSchema{
			Events: []LuaEvent{
				{Name: "on_entity_died", Tag: "entity_died"},
				{Name: "on_built_entity", Tag: "entity_built"},
				{Name: "on_robot_built_entity", Tag: "entity_built"},
				{Name: "on_player_mined_entity", Tag: "entity_mined"},
				{Name: "on_robot_mined_entity", Tag: "entity_mined"},
			},
			Fields: map[string]string{
				"Name":         "entity.name",
				"X":            "entity.position.x",
				"Y":            "entity.position.y",
				"UnitNumber":   "entity.unit_number",
				"SurfaceName":  "surface.name",
				"SurfaceIndex": "surface.index",
				"PlayerIndex":  "event.player_index",
				"Cause":        "cause",
			},
			Guards:       []string{"event.entity", "entity.surface"},
			Tag:          "entity_died",
			IncludeCause: true,
			Defaults: map[string]string{
				"UnitNumber":  "0",
				"PlayerIndex": "0",
				"Cause":       "",
			},
		},
	}

	var buf bytes.Buffer
	err := luaTemplate.Execute(&buf, schema)
	require.NoError(t, err)

	output := buf.String()
	t.Log(output)

	// Verify shared emit function
	assert.Contains(t, output, "local function emit_entity(tag, event, include_cause)")
	// Verify guards
	assert.Contains(t, output, "local entity = event.entity")
	assert.Contains(t, output, "if not (entity and entity.valid) then return end")
	assert.Contains(t, output, "local surface = entity.surface")
	assert.Contains(t, output, "if not (surface and surface.valid) then return end")
	// Verify include_cause logic
	assert.Contains(t, output, "if include_cause and event.cause and event.cause.valid then")
	assert.Contains(t, output, "cause = event.cause.name")
	// Verify handler functions
	assert.Contains(t, output, "local function on_entity_died(event)")
	assert.Contains(t, output, `emit_entity("entity_died", event, true)`)
	assert.Contains(t, output, `emit_entity("entity_built", event, false)`)
	assert.Contains(t, output, `emit_entity("entity_mined", event, false)`)
	// Verify registration
	assert.Contains(t, output, "entity_mod.events = {")
	assert.Contains(t, output, "[defines.events.on_entity_died] = on_entity_died,")
	assert.Contains(t, output, "[defines.events.on_built_entity] = on_built_entity,")
	assert.Contains(t, output, "return entity_mod")
}

